test('warm-up sets ramp below the working weight', () => {
  const program = generator.generate(programInput());
  const withWarmup = program.days
    .flatMap((d) => d.exercises)
    .find((e) => e.warmupSets > 0 && e.startingWeight);
  assert.ok(withWarmup);

  const warmups = withWarmup.prescribedSets.filter((s) => s.isWarmup);
  const working = withWarmup.prescribedSets.filter((s) => !s.isWarmup);
  assert.equal(warmups.length, withWarmup.warmupSets);
  assert.equal(working.length, withWarmup.sets);
  for (const set of warmups) {
    assert.ok((set.prescribedWeight ?? 0) < (withWarmup.startingWeight ?? 0));
  }
  for (const set of working) {
    assert.equal(set.prescribedWeight, withWarmup.startingWeight);
  }
});


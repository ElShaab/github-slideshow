test('cardio never exceeds fifteen minutes and falls as body fat improves', () => {
  const minutesAt = (bodyFatPercent: number): number => {
    const program = generator.generate(
      programInput({ goals: ['fat_loss'], bodyMetrics: { bodyFatPercent, muscleMassKg: 60 } }),
    );
    return Math.max(...program.days.map((d) => d.cardio?.minutes ?? 0));
  };

  const high = minutesAt(32);
  const mid = minutesAt(24);
  const low = minutesAt(14);

  assert.ok(high <= MAX_CARDIO_MINUTES, 'cardio exceeded the cap');
  assert.ok(high >= mid, `cardio should not rise as body fat falls (${high} vs ${mid})`);
  assert.ok(mid >= low, `cardio should not rise as body fat falls (${mid} vs ${low})`);
  assert.ok(low < high, 'leaner users should get less cardio');
});

test('cardio hits the specified duration at every body-fat anchor', () => {
  // The product spec fixes these four points. A goal must not move them — a
  // fat-loss bonus once pinned 27% and 24% both to the cap, so the user saw no
  // change for real progress.
  const anchors: Array<[number, number]> = [
    [27, 15],
    [24, 12],
    [21, 8],
    [18, 5],
  ];
  const goalSets: GoalType[][] = [
    ['muscle_gain'],
    ['fat_loss'],
    ['strength'],
    ['general_fitness'],
    ['recomposition'],
  ];

  for (const goals of goalSets) {
    for (const [bodyFatPercent, expected] of anchors) {
      assert.equal(
        baseCardioMinutes(bodyFatPercent, goals),
        expected,
        `${goals.join('+')} at ${bodyFatPercent}% body fat should get ${expected} minutes`,
      );
    }

    // And it never rises as the user gets leaner.
    const series = [32, 27, 24, 21, 18, 15, 12].map((bf) => baseCardioMinutes(bf, goals));
    for (let i = 1; i < series.length; i += 1) {
      assert.ok(
        series[i] <= series[i - 1],
        `${goals.join('+')} cardio rose as body fat fell: ${series.join(' -> ')}`,
      );
    }
  }
});

test('computes direct, secondary and effective weekly volume', () => {
  const program = generator.generate(programInput());
  const chest = program.volumeSummary.chest;

  assert.ok(chest.directSets > 0, 'no direct chest volume');
  assert.ok(chest.secondarySets > 0, 'pressing should pay into chest indirectly too');
  assert.equal(
    Math.round(chest.effectiveSets * 10) / 10,
    Math.round((chest.directSets + chest.secondarySets) * 10) / 10,
  );

  // Pressing volume must be charged to the triceps even with no direct work.
  assert.ok(program.volumeSummary.triceps.secondarySets > 0);
});

